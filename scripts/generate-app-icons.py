#!/usr/bin/env python3
"""Generates app/src/main/kotlin/com/qeetgroup/qeetid/ui/AppIcons.kt: the icons the screens need that Qeetrix for
Android doesn't have yet, from @qeetrix/icons' sharp-outline SVGs (the same Lucide outlines the web uses).

    scripts/generate-app-icons.py <path to @qeetrix/icons/dist/svg/sharp-outline>

Delete an icon here (and its uses) once Qeetrix for Android ships it.
"""
import pathlib
import re
import sys
import xml.etree.ElementTree as ET

ICONS = [
    "bell-ring", "bot-off", "download", "globe", "laptop", "monitor", "rotate-ccw", "shield-alert",
]

OUT = pathlib.Path(__file__).resolve().parent.parent / "app/src/main/kotlin/com/qeetgroup/qeetid/ui/AppIcons.kt"


def num(v):
    return float(v)


def fmt(v):
    s = f"{v:.3f}".rstrip("0").rstrip(".")
    return s if s != "-0" else "0"


def element_path(el):
    tag = el.tag.split("}")[-1]
    a = el.attrib
    if tag == "path":
        return a["d"]
    if tag == "circle":
        cx, cy, r = num(a["cx"]), num(a["cy"]), num(a["r"])
        return f"M{fmt(cx - r)} {fmt(cy)}a{fmt(r)} {fmt(r)} 0 1 0 {fmt(2 * r)} 0a{fmt(r)} {fmt(r)} 0 1 0 {fmt(-2 * r)} 0Z"
    if tag == "rect":
        x, y, w, h = num(a.get("x", 0)), num(a.get("y", 0)), num(a["width"]), num(a["height"])
        return f"M{fmt(x)} {fmt(y)}h{fmt(w)}v{fmt(h)}h{fmt(-w)}Z"
    if tag == "line":
        return f"M{a['x1']} {a['y1']}L{a['x2']} {a['y2']}"
    if tag in ("polyline", "polygon"):
        pts = re.split(r"[\s,]+", a["points"].strip())
        pairs = [f"{pts[i]} {pts[i + 1]}" for i in range(0, len(pts), 2)]
        return "M" + "L".join(pairs) + ("Z" if tag == "polygon" else "")
    if tag == "ellipse":
        cx, cy, rx, ry = num(a["cx"]), num(a["cy"]), num(a["rx"]), num(a["ry"])
        return f"M{fmt(cx - rx)} {fmt(cy)}a{fmt(rx)} {fmt(ry)} 0 1 0 {fmt(2 * rx)} 0a{fmt(rx)} {fmt(ry)} 0 1 0 {fmt(-2 * rx)} 0Z"
    raise SystemExit(f"unsupported element {tag}")


def camel(name):
    return "".join(p.capitalize() for p in name.split("-"))


def main():
    src = pathlib.Path(sys.argv[1])
    entries = []
    for name in ICONS:
        found = list(src.rglob(f"{name}.svg"))
        if not found:
            raise SystemExit(f"{name}.svg not found under {src}")
        root = ET.parse(found[0]).getroot()
        elements = []
        for el in root.iter():
            if el is root or el.tag.split("}")[-1] in ("title", "g", "defs"):
                continue
            filled = el.attrib.get("fill") == "currentColor"
            elements.append((element_path(el), filled))
        body = ",\n".join(f'            AppIconPath("{d}", fill = {"true" if f else "false"})' for d, f in elements)
        entries.append(f"    {camel(name)}(\n        listOf(\n{body},\n        ),\n    ),")
    OUT.write_text(TEMPLATE.replace("@ENTRIES@", "\n".join(entries)))
    print(f"wrote {OUT} ({len(ICONS)} icons)")


TEMPLATE = '''package com.qeetgroup.qeetid.ui

// Generated by scripts/generate-app-icons.py from @qeetrix/icons' sharp-outline SVGs. Do not edit by hand.

import androidx.compose.foundation.Image
import androidx.compose.foundation.layout.size
import androidx.compose.runtime.Composable
import androidx.compose.runtime.remember
import androidx.compose.ui.Modifier
import androidx.compose.ui.graphics.Color
import androidx.compose.ui.graphics.ColorFilter
import androidx.compose.ui.graphics.SolidColor
import androidx.compose.ui.graphics.StrokeCap
import androidx.compose.ui.graphics.StrokeJoin
import androidx.compose.ui.graphics.takeOrElse
import androidx.compose.ui.graphics.vector.ImageVector
import androidx.compose.ui.graphics.vector.addPathNodes
import androidx.compose.ui.graphics.vector.rememberVectorPainter
import androidx.compose.ui.unit.Dp
import androidx.compose.ui.unit.dp
import com.qeetgroup.qeetrix.foundation.sizing.QeetrixSize
import com.qeetgroup.qeetrix.theme.LocalQeetrixContentColor
import com.qeetgroup.qeetrix.theme.QeetrixTheme

/** One part of an icon: an outline, or a filled mark (a dot). */
class AppIconPath(
    val pathData: String,
    val fill: Boolean,
)

/**
 * Icons the screens need that Qeetrix for Android doesn't have yet: the same sharp Lucide outlines as the web's
 * `@qeetrix/icons`, drawn as [com.qeetgroup.qeetrix.icons.QeetrixIcon] draws its own (the theme's stroke, square ends,
 * mitred joins). Logged as a Qeetrix finding; each goes when Qeetrix for Android ships it.
 */
enum class AppIconName(
    val paths: List<AppIconPath>,
) {
@ENTRIES@
}

/** An [AppIconName], sized and tinted like a Qeetrix icon. */
@Composable
fun AppIcon(
    name: AppIconName,
    contentDescription: String?,
    modifier: Modifier = Modifier,
    size: Dp = QeetrixSize.IconMd,
    tint: Color = LocalQeetrixContentColor.current.takeOrElse { QeetrixTheme.colors.iconDefault },
) {
    val stroke = QeetrixTheme.density.iconStroke
    val vector = remember(name, stroke) { name.toImageVector(stroke) }
    Image(
        painter = rememberVectorPainter(vector),
        contentDescription = contentDescription,
        modifier = modifier.size(size),
        colorFilter = ColorFilter.tint(tint),
    )
}

private fun AppIconName.toImageVector(stroke: Float): ImageVector {
    val builder =
        ImageVector.Builder(
            defaultWidth = 24.dp,
            defaultHeight = 24.dp,
            viewportWidth = 24f,
            viewportHeight = 24f,
        )
    for (path in paths) {
        builder.addPath(
            pathData = addPathNodes(path.pathData),
            fill = if (path.fill) SolidColor(Color.Black) else null,
            stroke = SolidColor(Color.Black),
            strokeLineWidth = stroke,
            strokeLineCap = StrokeCap.Square,
            strokeLineJoin = StrokeJoin.Miter,
            strokeLineMiter = 4f,
        )
    }
    return builder.build()
}
'''

if __name__ == "__main__":
    main()

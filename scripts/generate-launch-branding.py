#!/usr/bin/env python3
"""Generates the launch screen's foot, "from" over "Qeet Group", as vector drawables: res/drawable/launch_branding.xml
(light) and res/drawable-night/launch_branding.xml (dark).

The Launch mockup (qeet-mockups, products/qeet-id, 01 Launch) sets them in Qeet Sans: "from" in body.sm (12/16) in
color.text.subtle, "Qeet Group" in body.lg (16/24) at weight 600 in color.text.default, space.gap.xs apart. The system
splash screen draws its branding image before the app runs, so it can't use a font: the words are the font's own glyph
outlines, shaped by HarfBuzz at the axes Qeetrix uses (opsz = the size, GEOM = font.geometry.body, wght), in the
200 x 80 dp box Android gives the branding image, centred, as CSS lays out each line's box.

    python3 -m venv .venv && .venv/bin/pip install fonttools uharfbuzz
    .venv/bin/python scripts/generate-launch-branding.py [path to qx_qeet_sans_vf.ttf]

The font defaults to Qeetrix for Android's copy in .qeetrix/. Run it again when the words, the type or the colours
change.
"""

import pathlib
import sys

import uharfbuzz as hb
from fontTools.pens.svgPathPen import SVGPathPen
from fontTools.pens.transformPen import TransformPen
from fontTools.ttLib import TTFont
from fontTools.varLib.instancer import instantiateVariableFont

ROOT = pathlib.Path(__file__).resolve().parent.parent
FONT = ROOT / ".qeetrix/qeetrix-android/qeetrix/src/main/res/font/qx_qeet_sans_vf.ttf"
RES = ROOT / "app/src/main/res"

# The system splash screen's branding image box, in dp.
BOX_WIDTH, BOX_HEIGHT = 200, 80
# Viewport units per dp: whole-number coordinates at 0.05 dp keep each glyph's path short.
UNITS = 20
# space.gap.xs between the two lines.
GAP = 4
# font.geometry.body: the GEOM axis for body text.
GEOM_BODY = 0

# (text, size, line height, weight, light colour, dark colour)
LINES = [
    # body.sm, color.text.subtle
    ("from", 12, 16, 400, "#484747", "#D1CFCE"),
    # body.lg at weight 600, color.text.default
    ("Qeet Group", 16, 24, 600, "#0E0D0D", "#F3F1EF"),
]


def number(value):
    text = str(round(value))
    return "0" if text == "-0" else text


def line_paths(font_bytes, text, size, line_top, line_height, weight):
    """The line's glyph outlines as path data, one per glyph (Android Lint wants short paths), centred in the box, the
    baseline where CSS puts it in its line box."""
    axes = {"wght": weight, "opsz": size, "GEOM": GEOM_BODY}
    # Shape at the axes, so advances and kerning are the instance's.
    face = hb.Face(font_bytes)
    shaper = hb.Font(face)
    shaper.set_variations(axes)
    buffer = hb.Buffer()
    buffer.add_str(text)
    buffer.guess_segment_properties()
    hb.shape(shaper, buffer, {"kern": True, "liga": True})

    instance = instantiateVariableFont(TTFont(FONT), axes, updateFontNames=False)
    upm = instance["head"].unitsPerEm
    ascent, descent = instance["hhea"].ascent, instance["hhea"].descent
    scale = size / upm
    # CSS: the content area (ascent + descent) sits in the middle of the line box; the baseline is ascent below its top.
    content = (ascent - descent) * scale
    baseline = line_top + (line_height - content) / 2 + ascent * scale

    width = sum(position.x_advance for position in buffer.glyph_positions) * scale
    x = (BOX_WIDTH - width) / 2
    glyph_set = instance.getGlyphSet()
    order = instance.getGlyphOrder()
    paths = []
    pen_x = 0
    for info, position in zip(buffer.glyph_infos, buffer.glyph_positions):
        origin_x = (x + (pen_x + position.x_offset) * scale) * UNITS
        origin_y = (baseline - position.y_offset * scale) * UNITS
        pen = SVGPathPen(glyph_set, ntos=number)
        glyph_set[order[info.codepoint]].draw(
            TransformPen(pen, (scale * UNITS, 0, 0, -scale * UNITS, origin_x, origin_y))
        )
        if pen.getCommands():
            paths.append(pen.getCommands())
        pen_x += position.x_advance
    return paths


def drawable(lines_paths, colours, theme):
    lines = [
        '<?xml version="1.0" encoding="utf-8"?>',
        "<!-- Generated by scripts/generate-launch-branding.py from Qeet Sans. Do not edit. -->",
        f'<!-- The launch screen\'s foot, "from Qeet Group", {theme}: the system splash screen\'s branding image. -->',
        '<vector xmlns:android="http://schemas.android.com/apk/res/android"',
        f'    android:width="{BOX_WIDTH}dp"',
        f'    android:height="{BOX_HEIGHT}dp"',
        f'    android:viewportWidth="{BOX_WIDTH * UNITS}"',
        f'    android:viewportHeight="{BOX_HEIGHT * UNITS}">',
    ]
    for paths, colour in zip(lines_paths, colours):
        for path in paths:
            lines += ["    <path", f'        android:fillColor="{colour}"', f'        android:pathData="{path}" />']
    lines.append("</vector>")
    return "\n".join(lines) + "\n"


def main():
    global FONT
    if len(sys.argv) > 1:
        FONT = pathlib.Path(sys.argv[1])
    font_bytes = FONT.read_bytes()
    block = sum(line[2] for line in LINES) + GAP * (len(LINES) - 1)
    top = (BOX_HEIGHT - block) / 2
    paths = []
    for text, size, line_height, weight, _, _ in LINES:
        paths.append(line_paths(font_bytes, text, size, top, line_height, weight))
        top += line_height + GAP
    for folder, index, theme in (("drawable", 4, "light"), ("drawable-night", 5, "dark")):
        out = RES / folder / "launch_branding.xml"
        out.parent.mkdir(exist_ok=True)
        out.write_text(drawable(paths, [line[index] for line in LINES], theme))
        print(f"wrote {out.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
